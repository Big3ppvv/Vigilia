/* Se calcula al elegir una mejora, nunca por enemigo ni por fotograma. */
export function objectBonuses(mem, rooms) {
  const result = {};
  const add = (bonus, level = 1) => {
    for (const [stat, value] of Object.entries(bonus)) result[stat] = (result[stat] || 0) + value * level;
  };
  for (const item of OBJECTS) if (mem[item.id] > 0) add(item.bonus, mem[item.id]);
  for (const collection of OBJECT_COLLECTIONS) if (rooms.has(collection.id)) add(collection.bonus);
  return result;
}
